#!/usr/bin/env python3
"""
Analyze trajectory continuity from JSON file generated by demo_drake_mujoco_cosim.

Computes position, velocity, acceleration, and jerk for each joint,
and checks for discontinuities (jumps) at the sampling level.
"""

import json
import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
from typing import Dict, List, Tuple

def load_trajectory(json_path: str) -> Tuple[np.ndarray, np.ndarray, float, int]:
    """Load trajectory from JSON file.

    Returns:
        time: time values (seconds)
        traj: trajectory values (num_timesteps x num_joints)
        control_period: control period (seconds)
        control_hz: control frequency (Hz)
    """
    with open(json_path, 'r') as f:
        data = json.load(f)

    # Extract control parameters
    actions = data['actions']
    if not actions:
        raise ValueError("No actions in JSON")

    params = actions[0]['taskParameters']
    control_hz = params['controlHz']
    control_period = params['controlPeriod']

    # Extract right hand trajectory (7 joints: indices 12-18)
    right_hand = params['rightHand']
    traj = np.array(right_hand)  # shape: (num_timesteps, 7)

    num_timesteps = traj.shape[0]
    time = np.linspace(0, control_period * (num_timesteps - 1), num_timesteps)

    return time, traj, control_period, control_hz

def compute_derivatives(time: np.ndarray, traj: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Compute velocity, acceleration, and jerk using central differences.

    Args:
        time: (T,) time values
        traj: (T, N) trajectory values

    Returns:
        velocity: (T, N) first derivative
        acceleration: (T, N) second derivative
        jerk: (T, N) third derivative
    """
    dt = np.diff(time)

    # Velocity: central difference
    velocity = np.zeros_like(traj)
    velocity[1:-1] = (traj[2:] - traj[:-2]) / (dt[1:] + dt[:-1])[:, None]
    # Forward/backward difference at boundaries
    velocity[0] = (traj[1] - traj[0]) / dt[0]
    velocity[-1] = (traj[-1] - traj[-2]) / dt[-1]

    # Acceleration: central difference of velocity
    acceleration = np.zeros_like(traj)
    acceleration[1:-1] = (velocity[2:] - velocity[:-2]) / (dt[1:] + dt[:-1])[:, None]
    acceleration[0] = (velocity[1] - velocity[0]) / dt[0]
    acceleration[-1] = (acceleration[-2] - acceleration[-1]) / dt[-1]

    # Jerk: central difference of acceleration
    jerk = np.zeros_like(traj)
    jerk[1:-1] = (acceleration[2:] - acceleration[:-2]) / (dt[1:] + dt[:-1])[:, None]
    jerk[0] = (acceleration[1] - acceleration[0]) / dt[0]
    jerk[-1] = (jerk[-2] - jerk[-1]) / dt[-1]

    return velocity, acceleration, jerk

def detect_discontinuities(deriv: np.ndarray, name: str, threshold: float = 5.0) -> List[int]:
    """Detect indices where derivative has a large jump.

    Args:
        deriv: (T, N) derivative values
        name: name of the derivative (for reporting)
        threshold: threshold for discontinuity (in units / sample)

    Returns:
        List of indices where discontinuity is detected
    """
    # Compute difference between consecutive samples
    diff = np.diff(deriv, axis=0)

    # Find jumps exceeding threshold
    # We use a robust measure: median absolute deviation
    mad = np.median(np.abs(diff - np.median(diff, axis=0)), axis=0)
    median_diff = np.median(diff, axis=0)

    # A jump is where the difference is far from the median
    # More than 10 MAD away is considered an outlier
    outliers = np.where(np.abs(diff - median_diff) > 10 * mad)[0]

    # Group consecutive outliers
    discontinuities = []
    if len(outliers) > 0:
        # Group consecutive indices
        groups = []
        current_group = [outliers[0]]
        for i in range(1, len(outliers)):
            if outliers[i] == outliers[i-1] + 1:
                current_group.append(outliers[i])
            else:
                groups.append(current_group)
                current_group = [outliers[i]]
        groups.append(current_group)

        # Report one representative per group
        for group in groups:
            discontinuities.append(group[0])

    return discontinuities

def analyze_continuity(json_path: str) -> Dict:
    """Analyze trajectory continuity.

    Returns:
        Dictionary containing analysis results
    """
    time, traj, control_period, control_hz = load_trajectory(json_path)
    num_timesteps, num_joints = traj.shape

    # Joint names (right arm joints 1-7)
    joint_names = [f'right_arm_joint{i}' for i in range(1, 8)]

    # Compute derivatives
    velocity, acceleration, jerk = compute_derivatives(time, traj)

    # Detect discontinuities
    velocity_discontinuities = []
    acceleration_discontinuities = []
    jerk_discontinuities = []

    for j in range(num_joints):
        v_disc = detect_discontinuities(velocity[:, j:j+1], 'velocity')
        a_disc = detect_discontinuities(acceleration[:, j:j+1], 'acceleration')
        j_disc = detect_discontinuities(jerk[:, j:j+1], 'jerk')

        if v_disc:
            velocity_discontinuities.append((j, v_disc))
        if a_disc:
            acceleration_discontinuities.append((j, a_disc))
        if j_disc:
            jerk_discontinuities.append((j, j_disc))

    # Compute statistics
    results = {
        'num_timesteps': num_timesteps,
        'duration': time[-1],
        'control_hz': control_hz,
        'control_period': control_period,
        'num_joints': num_joints,
        'joint_names': joint_names,
        'velocity_range': (velocity.min(axis=0), velocity.max(axis=0)),
        'acceleration_range': (acceleration.min(axis=0), acceleration.max(axis=0)),
        'jerk_range': (jerk.min(axis=0), jerk.max(axis=0)),
        'velocity_discontinuities': velocity_discontinuities,
        'acceleration_discontinuities': acceleration_discontinuities,
        'jerk_discontinuities': jerk_discontinuities,
        'max_velocity_jump': np.max(np.abs(np.diff(velocity, axis=0))),
        'max_acceleration_jump': np.max(np.abs(np.diff(acceleration, axis=0))),
        'max_jerk_jump': np.max(np.abs(np.diff(jerk, axis=0))),
    }

    return results, time, traj, velocity, acceleration, jerk

def print_analysis(results: Dict):
    """Print analysis results."""
    print("=" * 80)
    print("TRAJECTORY CONTINUITY ANALYSIS")
    print("=" * 80)
    print(f"Duration: {results['duration']:.4f} s")
    print(f"Control Hz: {results['control_hz']} Hz")
    print(f"Control Period: {results['control_period']*1000:.2f} ms")
    print(f"Timesteps: {results['num_timesteps']}")
    print(f"Joints: {results['num_joints']}")
    print()

    for i, name in enumerate(results['joint_names']):
        print(f"Joint {i+1}: {name}")
        v_min, v_max = results['velocity_range']
        a_min, a_max = results['acceleration_range']
        j_min, j_max = results['jerk_range']
        print(f"  Velocity range: [{v_min[i]:.4f}, {v_max[i]:.4f}] rad/s")
        print(f"  Acceleration range: [{a_min[i]:.4f}, {a_max[i]:.4f}] rad/s²")
        print(f"  Jerk range: [{j_min[i]:.4f}, {j_max[i]:.4f}] rad/s³")

    print()
    print("DISCONTINUITY ANALYSIS")
    print("-" * 40)

    if results['velocity_discontinuities']:
        print(f"⚠️  Velocity discontinuities detected at {len(results['velocity_discontinuities'])} joint(s)")
        for j, disc in results['velocity_discontinuities']:
            print(f"   {results['joint_names'][j]}: at sample(s) {disc}")
    else:
        print("✓ No velocity discontinuities detected")

    if results['acceleration_discontinuities']:
        print(f"⚠️  Acceleration discontinuities detected at {len(results['acceleration_discontinuities'])} joint(s)")
        for j, disc in results['acceleration_discontinuities']:
            print(f"   {results['joint_names'][j]}: at sample(s) {disc}")
    else:
        print("✓ No acceleration discontinuities detected")

    if results['jerk_discontinuities']:
        print(f"⚠️  Jerk discontinuities detected at {len(results['jerk_discontinuities'])} joint(s)")
        for j, disc in results['jerk_discontinuities']:
            print(f"   {results['joint_names'][j]}: at sample(s) {disc}")
    else:
        print("✓ No jerk discontinuities detected (C3 continuous)")

    print()
    print(f"Maximum velocity jump (between samples): {results['max_velocity_jump']:.6f} rad/s")
    print(f"Maximum acceleration jump: {results['max_acceleration_jump']:.6f} rad/s²")
    print(f"Maximum jerk jump: {results['max_jerk_jump']:.6f} rad/s³")
    print("=" * 80)

def plot_trajectories(json_path: str, output_path: str = None):
    """Plot position, velocity, acceleration, and jerk for all joints."""
    results, time, traj, velocity, acceleration, jerk = analyze_continuity(json_path)

    num_joints = results['num_joints']
    joint_names = results['joint_names']

    fig, axes = plt.subplots(4, 1, figsize=(12, 10), sharex=True)

    colors = plt.cm.tab10(np.linspace(0, 1, num_joints))

    # Position
    ax = axes[0]
    for i in range(num_joints):
        ax.plot(time, traj[:, i], label=joint_names[i], color=colors[i], alpha=0.7)
    ax.set_ylabel('Position (rad)')
    ax.set_title('Joint Positions')
    ax.legend(loc='upper right', fontsize=8, ncol=2)
    ax.grid(True, alpha=0.3)

    # Velocity
    ax = axes[1]
    for i in range(num_joints):
        ax.plot(time, velocity[:, i], color=colors[i], alpha=0.7)
    ax.set_ylabel('Velocity (rad/s)')
    ax.set_title('Joint Velocities')
    ax.grid(True, alpha=0.3)

    # Acceleration
    ax = axes[2]
    for i in range(num_joints):
        ax.plot(time, acceleration[:, i], color=colors[i], alpha=0.7)
    ax.set_ylabel('Acceleration (rad/s²)')
    ax.set_title('Joint Accelerations')
    ax.grid(True, alpha=0.3)

    # Jerk
    ax = axes[3]
    for i in range(num_joints):
        ax.plot(time, jerk[:, i], color=colors[i], alpha=0.7)
    ax.set_ylabel('Jerk (rad/s³)')
    ax.set_xlabel('Time (s)')
    ax.set_title('Joint Jerks')
    ax.grid(True, alpha=0.3)

    plt.tight_layout()

    if output_path:
        plt.savefig(output_path, dpi=150)
        print(f"Plot saved to {output_path}")
    else:
        plt.show()

def main():
    import sys
    if len(sys.argv) < 2:
        print("Usage: python analyze_trajectory_continuity.py <trajectory.json> [output.png]")
        print()
        json_files = list(Path('.').glob('trajectory_action_*.json'))
        if json_files:
            print(f"Found {len(json_files)} JSON file(s) in current directory:")
            for f in sorted(json_files):
                print(f"  {f}")
            print(f"Analyzing most recent: {sorted(json_files)[-1]}")
            json_path = str(sorted(json_files)[-1])
        else:
            print("No trajectory JSON files found in current directory")
            return
    else:
        json_path = sys.argv[1]

    print(f"\nAnalyzing: {json_path}\n")

    # Print analysis
    results, *_ = analyze_continuity(json_path)
    print_analysis(results)

    # Plot
    output_path = sys.argv[2] if len(sys.argv) > 2 else None
    plot_trajectories(json_path, output_path)

if __name__ == '__main__':
    main()
